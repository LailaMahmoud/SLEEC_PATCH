def build_prompt(
    issue_type,
    rules,
    findings,
    repair_operator,
    system_description="",
    existing_events=None,
    existing_measures=None,
    existing_responses=None
):
    prompt_builders = {
        "event_specialization": event_specialization_prompt,
        "measure_specialization": measure_specialization_prompt,
        "capability_refinement": capability_refinement_prompt,
        "new_rule_generation": new_rule_generation_prompt,
    }

    if repair_operator not in LLM_SEMANTIC_OPERATORS:
        raise ValueError(
            f"{repair_operator} is deterministic and must be generated "
            f"by Python script, not GPT."
        )

    builder = prompt_builders.get(repair_operator)

    if builder is None:
        raise ValueError(
            f"No prompt builder is registered for LLM semantic operator: "
            f"{repair_operator}"
        )

    return builder(
        issue_type=issue_type,
        rules=rules,
        findings=findings,
        system_description=system_description,
        existing_events=existing_events,
        existing_measures=existing_measures,
        existing_responses=existing_responses
    )


